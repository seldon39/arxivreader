let language = "fr";

export function setLanguage(value) {
  language = STRINGS[value] ? value : "fr";
  document.documentElement.lang = language;
  applyStatic(document);
}

export function getLanguage() {
  return language;
}

// Accord en nombre : clé.one pour 0 et 1 en français (1 seul en anglais), clé.other sinon
export function tn(key, n, params = {}) {
  const one = language === "fr" ? n <= 1 : n === 1;
  return t(`${key}.${one ? "one" : "other"}`, { n, ...params });
}

export function t(key, params = {}) {
  const text = STRINGS[language][key] ?? STRINGS.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? "");
}

// Traduit les éléments statiques marqués data-i18n / data-i18n-title / data-i18n-placeholder.
export function applyStatic(root) {
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}
